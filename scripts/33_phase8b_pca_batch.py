def bh(p: np.ndarray) -> np.ndarray:
    """Benjamini-Hochberg q-values."""
    p = np.asarray(p, float)
    n = len(p)
    o = np.argsort(p)
    q = np.empty(n)
    q[o] = np.minimum.accumulate((p[o] * n / np.arange(1, n + 1))[::-1])[::-1]
    return np.clip(q, 0, 1)


def kruskal_H_from_ranks(ranks: np.ndarray, onehot: np.ndarray) -> np.ndarray:
    """Kruskal-Wallis H for one or many rank vectors against fixed groups.

    `ranks` is (n,) or (m, n); `onehot` is (n, k). Permuting GROUP LABELS does
    not change the ranks, so the null can be generated by permuting rows of
    `ranks` -- which is what makes the permutation test cheap.
    """
    r = np.atleast_2d(ranks)
    n = r.shape[1]
    ni = onehot.sum(axis=0)
    Ri = r @ onehot                                   # (m, k) group rank sums
    H = 12.0 / (n * (n + 1)) * (Ri ** 2 / ni).sum(axis=1) - 3 * (n + 1)
    return H


def stratified_perm_indices(strata: np.ndarray, n_perm: int,
                            rng: np.random.Generator) -> np.ndarray:
    """(n_perm, n) index matrix permuting only WITHIN each stratum.

    Permuting within strata preserves the stratum x group composition, so the
    null says: 'no group structure BEYOND what composition already explains'.
    """
    n = len(strata)
    base = np.arange(n)
    out = np.empty((n_perm, n), dtype=np.int64)
    blocks = [np.where(strata == s)[0] for s in np.unique(strata)]
    for i in range(n_perm):
        idx = base.copy()
        for b in blocks:
            idx[b] = rng.permutation(b)
        out[i] = idx
    return out


