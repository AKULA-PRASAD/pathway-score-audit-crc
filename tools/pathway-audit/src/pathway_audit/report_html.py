"""Self-contained HTML report (no external assets, no JavaScript). Charts are inline SVG drawn here."""
from __future__ import annotations

import html
from pathlib import Path

CSS = """
:root{--paper:#fbfaf8;--ink:#1f2933;--ink2:#52606d;--line:#e4e7eb;--pass:#1f7a4d;--fail:#b42318;--bar:#2a78d6;--bar2:#c2366c;--warn:#8a5a10}
@media (prefers-color-scheme:dark){:root{--paper:#14161a;--ink:#eef0f3;--ink2:#a7b0bb;--line:#2b3038;--pass:#4cc28a;--fail:#f07a6e;--bar:#5b9cec;--bar2:#e46a95;--warn:#d9a441}}
*{box-sizing:border-box}body{margin:0;background:var(--paper);color:var(--ink);font:15px/1.55 system-ui,-apple-system,"Segoe UI",sans-serif;padding:24px 16px 64px}
main{max-width:980px;margin:0 auto}h1{font-size:1.7rem;margin:0 0 4px}h2{font-size:1.15rem;margin:32px 0 8px;border-bottom:1px solid var(--line);padding-bottom:4px}
h3{font-size:1rem;margin:20px 0 6px}.sub{color:var(--ink2)}table{border-collapse:collapse;width:100%;font-size:.9rem}th,td{text-align:left;padding:6px 8px;border-bottom:1px solid var(--line);vertical-align:top}
th{font-size:.75rem;text-transform:uppercase;letter-spacing:.05em;color:var(--ink2)}.badge{display:inline-block;padding:2px 8px;border-radius:4px;font-weight:600;font-size:.8rem;color:#fff}
.pass{background:var(--pass)}.fail{background:var(--fail)}.note{border-left:3px solid var(--warn);padding:6px 12px;color:var(--ink2);margin:10px 0}
svg text{fill:var(--ink);font-size:11px}svg .muted{fill:var(--ink2)}.wrap{overflow-x:auto}code{font-size:.85em}
"""


def _esc(x):
    return html.escape(str(x))


def _bar_chart(items, vmin=-1.0, vmax=1.0, width=640, label_w=170, color="var(--bar)", ci=None):
    """items: list of (label, value[, lo, hi]). Horizontal bars from 0."""
    h = 24 * len(items) + 30
    x = lambda v: label_w + (width - label_w - 60) * (v - vmin) / (vmax - vmin)
    out = [f'<svg viewBox="0 0 {width} {h}" width="100%" role="img" aria-label="bar chart">']
    for t in (vmin, (vmin + vmax) / 2, vmax) if vmin < 0 else (0, vmax / 2, vmax):
        out.append(f'<line x1="{x(t):.1f}" x2="{x(t):.1f}" y1="4" y2="{h-22}" stroke="var(--line)"/><text class="muted" x="{x(t):.1f}" y="{h-8}" text-anchor="middle">{t:g}</text>')
    for i, it in enumerate(items):
        lab, v = it[0], it[1]
        y = 10 + i * 24
        out.append(f'<text x="{label_w-8}" y="{y+12}" text-anchor="end">{_esc(lab)}</text>')
        if v is None:
            out.append(f'<text class="muted" x="{label_w+4}" y="{y+12}">not available</text>')
            continue
        x0, x1 = sorted((x(0), x(v)))
        out.append(f'<rect x="{x0:.1f}" y="{y+3}" width="{max(x1-x0,1):.1f}" height="13" rx="2" fill="{color}"/>')
        if len(it) >= 4 and it[2] is not None:
            out.append(f'<line x1="{x(it[2]):.1f}" x2="{x(it[3]):.1f}" y1="{y+9.5}" y2="{y+9.5}" stroke="var(--ink)" stroke-width="1.5"/>')
        out.append(f'<text x="{max(x1, x(it[3]) if len(it) >= 4 and it[3] is not None else x1)+6:.1f}" y="{y+13}">{v:+.2f}</text>')
    out.append("</svg>")
    return "".join(out)


def write_html(res: dict, out, title: str = "Pathway-score audit") -> Path:
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    q = res["qc"]
    P = [f"<!doctype html><html lang='en'><head><meta charset='utf-8'><meta name='viewport' content='width=device-width,initial-scale=1'><title>{_esc(title)}</title><style>{CSS}</style></head><body><main>",
         f"<h1>{_esc(title)}</h1><p class='sub'>{res['n_samples']} samples · {res['n_genes']} genes · generated by pathway-audit</p>"]
    P.append("<h2>1. Data-quality gate</h2>")
    P.append(f"<p><span class='badge {'pass' if q['passed'] else 'fail'}'>{'PASS' if q['passed'] else 'FAIL'}</span> median control-pair r = <b>{q['median_r']:.2f}</b> (threshold {q['threshold']})</p>")
    P.append("<div class='wrap'>" + _bar_chart([(k, v) for k, v in q["pairs"].items()], -1, 1) + "</div>")
    if not q["passed"]:
        P.append("<p class='note'>Control genes that co-express in virtually every bulk tumour dataset do not co-express here. Gene-level results below are not interpretable (likely a processing or probe-labelling defect).</p>")
    P.append("<h2>2. Verdicts</h2><div class='wrap'><table><tr><th>Gene set</th><th>Genes present</th><th>Verdict</th></tr>")
    for name, s in res["gene_sets"].items():
        c = s["coverage"]
        P.append(f"<tr><td><b>{_esc(name)}</b></td><td>{c['n_present']}/{c['n_genes']}</td><td>{'<br>'.join(_esc(v) for v in s['verdict'])}</td></tr>")
    P.append("</table></div>")
    for name, s in res["gene_sets"].items():
        if "top_genes" not in s:
            continue
        P.append(f"<h2>{_esc(name)}</h2>")
        P.append("<p class='sub'>Top genes (item–rest r): " + ", ".join(f"{_esc(g['gene'])} {g['item_rest_r']:.2f}" for g in s["top_genes"][:8]) + "</p>")
        if s.get("modules"):
            P.append("<p class='sub'>Modules: " + "; ".join(f"M{m['module']} ({m['n_genes']} genes, Jaccard {m['mean_jaccard']:.2f}, {m['stability']})" for m in s["modules"]) + "</p>")
        if "composition_rho" in s:
            P.append("<h3>Correlation with composition estimates (Spearman ρ)</h3><div class='wrap'>"
                     + _bar_chart(list(s["composition_rho"].items()), -1, 1, color="var(--bar2)") + "</div>")
            d = s.get("gene_disjoint_fibroblast_test")
            if d:
                P.append(f"<p class='sub'>Gene-disjoint fibroblast test: ρ {d['rho'][0]:.2f} ({d['rho'][1]:.2f}–{d['rho'][2]:.2f}), {d['n_shared_removed']} shared genes removed.</p>")
        ge = s.get("genotype_effects") or {}
        rows = [(k, e) for k, e in ge.items() if "unadjusted" in e]
        if rows:
            P.append("<h3>Genotype effects (difference in score SD; bootstrap 95 % CI)</h3><div class='wrap'>")
            items = []
            for k, e in rows:
                u = e["unadjusted"]
                items.append((f"{k} · unadjusted", u[0], u[1], u[2]))
                if "adjusted" in e:
                    a = e["adjusted"]
                    items.append((f"{k} · adjusted", a[0], a[1], a[2]))
            lim = max(1.0, max(abs(v) for it in items for v in it[1:] if v is not None) * 1.1)
            P.append(_bar_chart(items, -lim, lim) + "</div><table><tr><th>Annotation</th><th>n (+/−)</th><th>Verdict</th></tr>")
            for k, e in ge.items():
                P.append(f"<tr><td>{_esc(k)}</td><td>{e['n_pos']}/{e['n_neg']}</td><td>{_esc(e['verdict'])}</td></tr>")
            P.append("</table>")
    if res.get("pairwise"):
        P.append("<h2>3. Relationships between scores</h2><div class='wrap'><table><tr><th>Pair</th><th>Spearman</th><th>Partial given composition</th><th>Random-set null 95 %</th><th>Exceeds null</th></tr>")
        for p in res["pairwise"]:
            lo, hi = p["null_95_for_first_set"]
            P.append(f"<tr><td>{_esc(p['pair'])}</td><td>{p['spearman']:+.2f}</td><td>{p['partial_given_composition']:+.2f}</td><td>{lo:+.2f} to {hi:+.2f}</td><td>{'yes' if p['exceeds_null'] else 'no'}</td></tr>")
        P.append("</table></div>")
    if res.get("survival_screen"):
        s = res["survival_screen"]
        P.append(f"<h2>4. Survival screen</h2><p>Apparent ΔC {s['apparent_delta_C']:+.4f}; optimism {s['optimism_delta']:+.4f}; <b>corrected ΔC {s['corrected_delta_C']:+.4f}</b> "
                 f"(n {s['n']}, events {s['events']}, B {s['B']}). {_esc(s['note'])}.</p>")
    P.append("<h2>Interpretation limits</h2><ul><li>Scores are averaged bulk mRNA: not pathway activity, protein function or cell-type-specific expression.</li>"
             "<li>Composition values are computational estimates from the same data, not measured fractions.</li>"
             "<li>Adjusted effects can be over-adjusted when composition lies on the biological path.</li></ul></main></body></html>")
    path = out / "report.html"
    path.write_text("\n".join(P), encoding="utf-8")
    return path
