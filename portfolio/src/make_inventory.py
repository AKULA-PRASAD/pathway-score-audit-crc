"""Write portfolio/ASSET_INVENTORY.md: every portfolio file with size and SHA-256, plus the frozen sources it draws on."""
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
P = ROOT / "portfolio"
SOURCES = [
    "reports/figures/final/figure_values.json", "reports/figures/final/Fig1_study_design_cohort.png",
    "reports/figures/final/Fig2_preprocessing_qc.png", "reports/figures/final/Fig5_clinical_model.png",
    "reports/figures/final/FigS1_monte_carlo_precision.png", "reports/figures/final/FigS2_informative_censoring.png", "reports/phase9/execution/phase9_execution_results.json",
    "reports/phase9/execution_s7/phase9_s7_results.json", "reports/phase9/corrected_rerun_report/corrected_interval_results.json",
    "config/pathways/m2_panel_4set.json", "config/pathways/m2_panel_5set.json", "reports/phase8c/score_vs_annotation.csv",
    "reports/phase8c/representation_sensitivity.csv", "docs/PHASE8C_FROZEN_PATHWAY_SCORE_ANALYSIS.md",
    "docs/PHASE8B_PCA_BATCH_INVESTIGATION.md", "docs/PHASE6C_PATHWAY_PANEL_REVIEW.md", "docs/PHASE5_VALIDATION_PRECISION_ASSESSMENT.md",
    "reports/exploratory/validation_checks.json", "reports/exploratory/x1_molecular_anchoring/anchoring_tests.csv",
    "reports/exploratory/x3_batch/x3_summary.json", "reports/exploratory/x6_scores_vs_composition/score_composition_spearman.csv",
    "reports/exploratory/x8_external_audit/eligibility_table.csv",
]
ROLE = {
    "README.md": "portfolio-facing overview", "SPEAKER_NOTES.md": "speaker notes (generated by make_deck.py)",
    "PORTFOLIO_QC_REPORT.md": "quality-control report (generated by qc_check.py)", "requirements-portfolio.txt": "packages for rebuilding portfolio assets",
    "presentation/GSE39582_recurrence_portfolio.pptx": "editable presentation (19 slides + 2 appendix slides)",
    "presentation/GSE39582_recurrence_portfolio.pdf": "PDF presentation", "src/values.py": "reads every portfolio number from frozen outputs",
    "src/make_diagrams.py": "builds D1–D5", "src/make_slide_visuals.py": "builds slide visuals V01–V19 (original vector drawings)", "src/make_deck.py": "builds PPTX, PDF and speaker notes", "src/qc_check.py": "portfolio QC",
    "src/make_inventory.py": "writes this inventory",
    "src/web_check.py": "runs web interaction and accessibility checks in headless Chrome",
    "src/build_site.py": "builds the public GitHub Pages site from web/index.html and the deck PDF",
    "src/web_interaction_test.html.part": "the web checks appended by web_check.py",
    "web/index.html": "interactive research portfolio (source of the published web page)",
    "RESEARCH_REPORT.md": "standalone research report", "INTERVIEW_PREPARATION.md": "modelling explanations and interview question bank",
    "REPRODUCIBILITY_GUIDE.md": "tested reproduction commands", "SKILLS_EVIDENCE_AND_ROLE_FIT.md": "skills-to-evidence matrix and role fit",
    "PORTFOLIO_COMPLETION_REPORT.md": "completion matrix and readiness judgement",
    "RESUME_AND_LINKEDIN.md": "evidence-backed resume bullets and LinkedIn text",
}


def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


rows = []
for f in sorted(P.rglob("*")):
    if f.is_file() and f.name != "ASSET_INVENTORY.md" and "__pycache__" not in f.parts and not f.name.startswith("~$") and f.name != ".DS_Store":
        rel = f.relative_to(P).as_posix()
        names = {"D1": "D1 biological rationale", "D2": "D2 processing and feature engineering", "D3": "D3 pathway interpretation",
                 "D4": "D4 heterogeneity and limitations (conceptual)", "D5": "D5 model comparison and uncertainty"}
        dname = names.get(f.name[:2], "diagram")
        if rel.startswith("diagrams/slides/"):
            dname = f"slide visual {f.stem}"
        role = ROLE.get(rel, f"{dname} (editable SVG)" if rel.endswith(".svg") else f"{dname} (rendered PNG, 200 dpi)" if rel.endswith(".png") else "")
        rows.append(f"| `{rel}` | {role} | {f.stat().st_size:,} | `{sha(f)[:16]}…` |")
REQUIRED = ["README.md", "RESEARCH_REPORT.md", "INTERVIEW_PREPARATION.md", "REPRODUCIBILITY_GUIDE.md", "SKILLS_EVIDENCE_AND_ROLE_FIT.md",
            "PORTFOLIO_QC_REPORT.md", "PORTFOLIO_COMPLETION_REPORT.md", "SPEAKER_NOTES.md", "web/index.html",
            "presentation/GSE39582_recurrence_portfolio.pptx", "presentation/GSE39582_recurrence_portfolio.pdf"] + \
           [f"diagrams/{d}.{x}" for d in ("D1_biological_rationale", "D2_processing_feature_engineering", "D3_pathway_interpretation",
                                           "D4_heterogeneity_limitations", "D5_model_comparison_uncertainty") for x in ("svg", "png")] + \
           [f"diagrams/slides/{v}.{x}" for v in ("V01_cover_illustration", "V02_problem_question", "V03_biology_map", "V04_wnt", "V05_e2f",
                                                  "V06_p53", "V07_emt", "V08_bulk_tissue", "V10_preprocessing_panel", "V11_model_architecture",
                                                  "V12_nested_bootstrap", "V13_central_result", "V14_forest", "V15_robustness",
                                                  "V16_project_established", "V17_decisions_audit", "V18_conclusion_questions", "V19_solution_tool") for x in ("svg", "png")]
paths = [r.split("`")[1] for r in rows]
dups = sorted({x for x in paths if paths.count(x) > 1})
missing = [r for r in REQUIRED if r not in paths]
unknown_role = [x for x, r in zip(paths, rows) if "|  |" in r]
if dups or missing or unknown_role:
    raise SystemExit(f"inventory error: duplicates={dups} missing={missing} no-role={unknown_role}")
for s_ in SOURCES:
    if not (ROOT / s_).is_file():
        raise SystemExit(f"inventory error: source missing {s_}")
out = ["# Portfolio asset and source inventory", "",
       "All files under `portfolio/`. Generated assets are derived from frozen project outputs only; no model was fitted. "
       "The 579,716,096-byte checkpoint archive is not duplicated here; it remains the GitHub Release asset described in `docs/LARGE_ARTIFACT_ARCHIVE.md`.", "",
       "| File | Role | Bytes | SHA-256 (first 16) |", "|---|---|---:|---|", *rows, "",
       "## Frozen sources read (not modified)", "", "| Source | SHA-256 (first 16) |", "|---|---|",
       *[f"| `{s}` | `{sha(ROOT / s)[:16]}…` |" for s in SOURCES], ""]
(P / "ASSET_INVENTORY.md").write_text("\n".join(out), encoding="utf-8")
print(len(rows), "portfolio files (no duplicates, all required deliverables present);", len(SOURCES), "sources")
